#!/usr/bin/env python3
"""Generate quality/audit_trend.md: one row per night from nightly/*_adjudication.json, plus the gold_history rows.
Usage: trend.py [--nightly-dir DIR] [--history PATH] [--out PATH]"""
import argparse
import glob
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))


def load(p):
    with open(p) as f:
        return json.load(f)


def pct(s):
    m = re.search(r"(\d+(?:\.\d+)?)%", str(s or ""))
    return float(m.group(1)) if m else None


def night_type(d):
    return "extraction" if d.get("extraction_night") else "pause" if d.get("pause_night") else "hold" if d.get("hold_night") else "extraction"


def night_row(path, nightly_dir):
    d = load(path)
    night = d.get("night") or os.path.basename(path).split("_")[0]
    adj = d.get("adjudicated") or {}
    aud = d.get("as_audited") or {}
    stored = adj.get("stored") or aud.get("stored")
    correct, wrong = adj.get("correct"), adj.get("wrong")
    real = round(100 * (correct + wrong) / stored, 1) if stored and correct is not None and wrong is not None else None
    classes = 0
    for f in glob.glob(os.path.join(nightly_dir, night + "_[AB].json")):
        classes += len(load(f).get("_classes") or [])
    pd = str(d.get("pause_decision") or "")
    return {"night": night, "type": night_type(d), "stored": stored, "strict": pct(adj.get("precision_strict") or aud.get("precision_strict")),
            "real": real, "recall": pct(adj.get("recall") or aud.get("recall")), "classes": classes, "pause": pd}


def f(v):
    return "" if v is None else str(v)


def build(nightly_dir, history):
    rows = sorted((night_row(p, nightly_dir) for p in glob.glob(os.path.join(nightly_dir, "*_adjudication.json"))), key=lambda r: r["night"])
    out = ["# Audit trend", "", "Generated by `python3 quality/trend.py`. Do not edit by hand.", "",
           "## Nightly 20-law audits (adjudicated; precision and recall in %)", "",
           "| Night | Type | Stored | Strict | Real | Recall | Classes | Pause decision |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['night']} | {r['type']} | {f(r['stored'])} | {f(r['strict'])} | {f(r['real'])} | {f(r['recall'])} | {r['classes']} | {r['pause'].replace('|', '/')} |")
    out += ["", "## Gold set score history (full gold, every record in gold laws)", "",
            "| Night | Gold laws | Stored | Strict | Real | Recall | Not-real still stored | Effective-date accuracy | Previous strict |", "|---|---|---|---|---|---|---|---|---|"]
    if os.path.exists(history):
        with open(history) as fh:
            for l in fh:
                if l.strip():
                    g = json.loads(l)
                    out.append(f"| {g['night']} | {g['gold_laws']} | {g['stored']} | {g['precision_strict']} | {g['precision_real']} | {g['recall']} | "
                               f"{g['not_real_still_stored']} | {f(g['effective_date_accuracy'])} | {f(g['prev_strict'])} |")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--nightly-dir", default=os.path.join(HERE, "nightly"))
    ap.add_argument("--history", default=os.path.join(HERE, "gold_history.jsonl"))
    ap.add_argument("--out", default=os.path.join(HERE, "audit_trend.md"))
    a = ap.parse_args(argv)
    md = build(a.nightly_dir, a.history)
    with open(a.out, "w") as fh:
        fh.write(md)
    print(md)


if __name__ == "__main__":
    main()
